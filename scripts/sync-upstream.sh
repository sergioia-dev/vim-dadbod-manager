#!/usr/bin/env bash
# Re-vendor the vim-dadbod-ui runtime files that vim-dadbod-manager ships.
#
#   ./scripts/sync-upstream.sh <source-dir> [version] [revision]
#
# <source-dir> is a vim-dadbod-ui checkout, or the store path of the nixpkgs
# package:
#
#   nix build --no-link --print-out-paths 'nixpkgs#vimPlugins.vim-dadbod-ui'
#
# The vendored files are listed explicitly instead of copied wholesale: a
# `cp -R autoload` would delete this plugin's own autoload/dbui_multidb*, and a
# file upstream adds has to be vendored on purpose rather than appear in the tree
# unnoticed.
#
# A destination file that no longer matches scripts/vendored-files.sha256 has
# been edited locally, which is a mistake: re-run with FORCE=1 to overwrite it.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="${1:-}"
version="${2:-}"
revision="${3:-}"

if [[ -z "$src" || ! -d "$src" ]]; then
  echo "usage: sync-upstream.sh <vim-dadbod-ui source dir> [version] [revision]" >&2
  exit 2
fi

# "<path in vim-dadbod-ui>" or "<path in vim-dadbod-ui>:<path in this plugin>".
entries=(
  "autoload/db_ui.vim"
  "autoload/db_ui/connections.vim"
  "autoload/db_ui/dbout.vim"
  "autoload/db_ui/drawer.vim"
  "autoload/db_ui/notifications.vim"
  "autoload/db_ui/query.vim"
  "autoload/db_ui/schemas.vim"
  "autoload/db_ui/table_helpers.vim"
  "autoload/db_ui/utils.vim"
  "plugin/db_ui.vim"
  "ftplugin/dbui.vim"
  "ftplugin/dbout.vim"
  "ftplugin/sql.vim"
  "ftplugin/javascript.vim"
  "ftplugin/mysql.vim"
  "ftplugin/plsql.vim"
  "syntax/dbui.vim"
  "doc/dadbod-ui.txt"
  "LICENSE:LICENSE.vim-dadbod-ui"
)

manifest="$root/scripts/vendored-files.sha256"
dest_for() { printf '%s\n' "${1#*:}"; }
rel_for() { printf '%s\n' "${1%%:*}"; }

for entry in "${entries[@]}"; do
  rel="$(rel_for "$entry")"
  dest="$(dest_for "$entry")"
  srcfile="$src/$rel"
  destfile="$root/$dest"

  if [[ ! -f "$srcfile" ]]; then
    echo "sync-upstream.sh: $srcfile not found" >&2
    exit 1
  fi

  if [[ -f "$destfile" && -f "$manifest" && "${FORCE:-0}" != "1" ]]; then
    recorded="$(awk -v path="$dest" '$2 == path { print $1 }' "$manifest")"
    current="$(sha256sum "$destfile" | cut -d' ' -f1)"
    if [[ -n "$recorded" && "$recorded" != "$current" ]]; then
      echo "sync-upstream.sh: $dest does not match $manifest." >&2
      echo "Vendored files are not edited in place; re-run with FORCE=1 to overwrite." >&2
      exit 1
    fi
  fi

  install -D -m 0644 "$srcfile" "$destfile"
done

# The notification overlay is generated, not vendored: the vendored notification
# module with its hardcoded label ("[DBUI]") replaced by a settings lookup, so this
# plugin can label notifications "[DBManager]" without editing a vendored file. Vim
# will not let any other script define db_ui#notifications#* (E746), so the
# relabelled module has to be a copy at the same autoload path, never a wrapper.
# The overlay is regenerated here on every sync, and the difference is checked
# rather than trusted: a hand edit to it is pointless.
overlay_rel="notify-overlay/autoload/db_ui/notifications.vim"
overlay_old="let s:title = '[DBUI]'                    \"Title of notification"
overlay_new="let s:title = get(g:, 'db_ui_notification_title', '[DBUI]')  \"Title of notification"

if [[ "$(sed -n '10p' "$root/autoload/db_ui/notifications.vim")" != "$overlay_old" ]]; then
  echo "sync-upstream.sh: line 10 of autoload/db_ui/notifications.vim is no longer that label." >&2
  echo "The overlay would be generated wrong; update $overlay_rel and this script." >&2
  exit 1
fi

mkdir -p "$root/$(dirname "$overlay_rel")"
sed "10s|.*|$overlay_new|" "$root/autoload/db_ui/notifications.vim" > "$root/$overlay_rel"

overlay_changed="$(diff "$root/autoload/db_ui/notifications.vim" "$root/$overlay_rel" | grep -c '^[<>]' || true)"
if [[ "$overlay_changed" != "2" ]]; then
  echo "sync-upstream.sh: $overlay_rel differs from the vendored module on $overlay_changed lines (expected 2: one changed line)." >&2
  exit 1
fi

# The header comment carries the pinned revision; sha256sum -c skips it.
{
  if [[ -n "$version" || -n "$revision" ]]; then
    echo "# vim-dadbod-ui ${version:-unknown} @ ${revision:-unknown} — generated by scripts/sync-upstream.sh"
  elif [[ -f "$manifest" ]]; then
    head -n 1 "$manifest"
  else
    echo "# vim-dadbod-ui unknown @ unknown — generated by scripts/sync-upstream.sh"
  fi
  for entry in "${entries[@]}"; do
    dest="$(dest_for "$entry")"
    (cd "$root" && sha256sum "$dest")
  done
} > "$manifest.tmp"
mv "$manifest.tmp" "$manifest"

# doc/tags is generated, not vendored: it depends on the editor that built it.
if command -v nvim > /dev/null 2>&1; then
  (cd "$root" && nvim --clean --headless -c 'helptags doc' -c 'qall!') > /dev/null 2>&1
elif command -v vim > /dev/null 2>&1; then
  (cd "$root" && vim -N -u NONE -es -c 'helptags doc' -c 'qall!') > /dev/null 2>&1
fi

echo "vendored vim-dadbod-ui from $src"
(cd "$root" && git status --short -- autoload plugin ftplugin syntax doc notify-overlay LICENSE.vim-dadbod-ui scripts/vendored-files.sha256) || true
echo
echo "next: cd plugins/vim-dadbod-manager && ./test/run.sh && nix build . && git add the new files"
